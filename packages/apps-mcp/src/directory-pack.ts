function hints(t: ToolCatalogueEntry): string {
  return `readOnlyHint: ${t.readOnlyHint}, destructiveHint: ${t.destructiveHint}, idempotentHint: ${t.idempotentHint}, openWorldHint: ${t.openWorldHint}`;
}

function toolDetails(tools: ToolCatalogueEntry[]): string {
  return tools
    .map((t) => [`### \`${t.name}\` — ${t.title}`, '', t.description, '', `- Annotations: ${hints(t)}`, `- Scope: ${t.scope ?? 'none (anonymous endpoint)'}`, `- Available: ${t.surface === 'local' ? 'local `create mcp` only (not listed remotely)' : t.surface === 'anonymous' ? `${ANON_URL} only` : `${MCP_URL} (and \`create mcp\`)`}`].join('\n'))
    .join('\n\n');
}

