/** Every file of the pack, path (relative to the repository root) → content. */
export function directoryPack(): Record<string, string> {
  const all = toolCatalogue();
  const remote = all.filter((t) => t.surface === 'remote');
  const file = (name: string) => `${DIRECTORY_PACK_DIR}/${name}`;
  return {
    [file('README.md')]: `${GENERATED}\n\n${README}`,
    [file('claude-connectors-directory.md')]: claudeMarkdown(remote),
    [file('chatgpt-app.md')]: chatgptMarkdown(remote),
    [file('test-cases.md')]: testCasesMarkdown(),
    [file('security-and-privacy.md')]: `${GENERATED}\n\n${SECURITY}`,
    [file('reviewer-demo-account.md')]: `${GENERATED}\n\n${REVIEWER}`,
    [file('tools.json')]: `${JSON.stringify({ generatedFrom: 'packages/apps-mcp/src/tools.ts', server: MCP_URL, anonymousServer: ANON_URL, tools: all }, null, 2)}\n`,
  };
}
