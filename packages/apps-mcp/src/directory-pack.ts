function testCasesMarkdown(): string {
  const row = (c: { prompt: string; expect: readonly string[]; outcome: string }, i: number) => `| ${i + 1} | ${c.prompt.replace(/\|/g, '\\|')} | ${c.expect.length ? c.expect.map((e) => `\`${e}\``).join(', ') : '—'} | ${c.outcome.replace(/\|/g, '\\|')} |`;
  return [
    GENERATED,
    '',
    '# Test cases and example prompts',
    '',
    `Every tool named below exists in the registry (checked by the test that generates this file). Run them against the reviewer demo account (\`reviewer-demo-account.md\`) on ${MCP_URL}.`,
    '',
    `## Positive (${TEST_CASES.positive.length})`,
    '',
    '| # | Prompt | Tools expected | Expected outcome |',
    '|---|---|---|---|',
    ...TEST_CASES.positive.map(row),
    '',
    `## Negative (${TEST_CASES.negative.length})`,
    '',
    '| # | Prompt | Tools expected | Expected outcome |',
    '|---|---|---|---|',
    ...TEST_CASES.negative.map(row),
    '',
    '## Example prompts for the listing (Claude asks for at least three)',
    '',
    ...TEST_CASES.positive.slice(0, 4).map((c) => `- "${c.prompt}"`),
    '',
  ].join('\n');
}

const SECURITY = `# Security and privacy statement (for both directories)

**Publisher**: Create (create.com). **Support**: support@create.com. **Privacy policy**: ${PRIVACY}. **Terms**: ${TERMS}. **Data Processing Addendum**: ${DPA}. **Website**: https://www.create.com. *(Founder: confirm the support address and that the publisher name on the OpenAI Platform verification matches these pages.)*

## What the connector can reach

- Only Create app hosting (projects, services, deployments, variables, domains) in the ONE account the person picks on Create's consent screen, and by default only the projects the connection itself creates.
- Nothing in Create Commerce (stores, orders, customers) — that API uses a different token type the hosting MCP never accepts.

## Authorization

- OAuth 2.1 with PKCE (S256), per the MCP authorization specification (revision 2026-07-28): Protected Resource Metadata (RFC 9728), authorization server metadata (RFC 8414), resource indicators (RFC 8707) — tokens are audience-bound to ${MCP_URL} and refused anywhere else; the server never forwards a token.
- The consent screen states the account, the project scope, every permission, what the connection can never do, a monthly spend limit (default $20 on Pro, $0 extra on Hobby) and a size ceiling.
- Access tokens are opaque, stored only as SHA-256, and revocable from Account › Apps › Access; signing out everywhere, changing the password or removing a second factor revokes every connection.

## Data handling

- Tool calls are processed in Create's API; every mutating call writes an account audit row (who, which connection, what — never a variable's value).
- Secret values are sealed at rest, write-only (no tool or API returns them), and redacted from build logs.
- Create does not use tool-call content to train models. Deployed code and files are the customer's and are processed only to build and serve them.
- Web Analytics (\`set_analytics\` / \`get_analytics\`) is off until the account turns it on per project. It sets no cookies and uses no browser storage or fingerprinting, and stores no IP address: visitors are counted with a hash salted by a random value held only in memory and replaced every UTC day. It keeps the path (no query string), the referrer's host, UTM source/medium/campaign, country, device class and Web Vitals; honours Do Not Track and Global Privacy Control; is never active on anonymous previews; shows 30 days (Hobby) or 90 days (Pro); the points are stored by Cloudflare Workers Analytics Engine for up to about three months and expire on that schedule (turning analytics off stops collection; it does not delete stored points early). Path segments that look like emails or tokens are masked.
- Preview protection (\`set_protection\`, \`get_protection\`, \`revoke_share_link\`): share links are created only by a signed-in person in the Create dashboard, never through this connector, and are stored only as SHA-256 hashes; passwords are stored as argon2id hashes and never returned; the automation bypass secret can only be created by a signed-in person in the dashboard, never through this connector. Visitors to a protected preview get an HttpOnly, host-only cookie that the customer's app never receives.
- Preview comments (\`list_comments\`, \`reply_comment\`, \`resolve_comment\`): comments are written by members of the owning account on its protected previews and are visible only to members who can view the project; this connector reads them, replies and resolves or reopens threads under the project scope of the connection, and never reads screenshots. Comment text is returned as data; replies are plain text and are recorded in the account's audit log without their text.
- Firewall and static egress (\`get_firewall\`, \`set_firewall\`, \`add_firewall_rule\`, \`delete_firewall_rule\`, \`get_static_egress\`, \`set_static_egress\`): every rule is validated by Create (exact values and plain prefixes only, never a regular expression; lists are capped) and every change is recorded in the account's audit log. Rules run at Create's edge before the customer's app; the human check (challenge) uses Cloudflare Turnstile and a host-only, HttpOnly clearance cookie the app never receives, and the firewall stores no visitor data. Turning static egress on reserves a paid address, after the spending limit is checked.
- Compose import (\`preview_compose_import\`, \`apply_compose_import\`): Create reads only the compose text sent in the call and the values and secrets sent with it — never a file on disk, the server's environment or a URL named in the file (image references are validated, build URLs refused). Privileged containers, host mounts, added capabilities and host networking are refused with a named reason. Secret values are sealed and never appear in a preview, a result or the audit log. The preview creates nothing; the apply creates everything or nothing and is audited.
- Moving a project from Vercel (\`list_vercel_projects\`, \`preview_vercel_import\`, \`apply_vercel_import\`, \`get_import_status\`): the Vercel access token is given only by a signed-in person in the Create dashboard, never through this connector; Create keeps it encrypted for at most 24 hours, uses it only to read, and deletes it as soon as an import is applied. Create calls only Vercel's fixed API address, and data copies only read from Vercel Blob, Neon and Upstash addresses named by Vercel. Secret values are sealed and never appear in a preview, a result or the audit log. The preview creates nothing; the apply creates everything or nothing and is audited. Connecting the GitHub repository is left to a person in the dashboard.
- Sandboxes (\`create_sandbox\`, \`run_in_sandbox\`, \`write_sandbox_file\`, \`read_sandbox_file\`, \`list_sandbox_files\`, \`expose_sandbox_port\`, \`snapshot_sandbox\`, \`list_sandbox_snapshots\`, \`stop_sandbox\`, \`delete_sandbox_snapshot\`, \`list_sandboxes\`): each sandbox is its own microVM or gVisor sandbox on machines separate from customers' apps, with a read-only system, no credentials inside, no network unless the caller asks on a paid plan (and then only the public internet, from an address used only by sandboxes, never Create's or other customers' networks), and a hard lifetime after which it and its files are deleted. A connection reaches only the sandboxes it created. Create's audit log records each command's program name, argument count and a keyed hash (HMAC) of its arguments — never the arguments, environment values, file paths or contents, or output; output is kept, encrypted, for ten minutes after a command ends. Exposed ports are reachable only through signed links that expire within an hour.
- Private networking (\`get_private_networking\`, \`set_service_visibility\`, \`rotate_private_keys\`): a service made private is reachable only by the same project environment's edge frontends (through Create's own network, with a per-deployment token Create mints and never shows to the connector) and by the environment's other services. Tokens and signing keys never appear in tool results; signing keys are stored encrypted and every change is recorded in the account's audit log. Opening a database to the edge is for a signed-in person in the dashboard or CLI, never this connector.
- Billing: \`get_usage\` shows the account's plan, usage and spending only when the person who connected the app has billing access to the account (a narrow connection sees its own projects' usage only). \`set_spend_cap\` needs that billing access AND a connection the owner made account-wide with a second factor. No tool buys, upgrades or cancels a plan; the spending limit is on by default and, when reached, pauses sites and containers without deleting any data.

## Anonymous endpoint (${ANON_URL})

- No sign-in and no token; it can only create a preview deploy and read that preview's status. It cannot read or change any account.
- Previews serve built static files only (no builds, no Worker or server code), live on a separate registrable domain, carry a notice banner on every HTML page (a notice, not a phishing control), are served with no cookies, nosniff, no framing and other document types sandboxed, get no secrets or custom domains, are rate-limited per network, screened against an abuse blocklist, and are deleted after 72 hours unless claimed. The claim link is shown once, travels only in the URL fragment, and is stored only as SHA-256.

## Compliance

SOC 2, ISO 27001 and HIPAA controls are Create's standing target (audit logging, least privilege, encryption at rest for secrets, access review via the Access page). No certification is claimed in this submission.
`;

